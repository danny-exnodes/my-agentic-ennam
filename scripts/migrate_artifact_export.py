#!/usr/bin/env python3
"""Convert the old claude.ai Agent Ops artifact export into seed data for the Supabase schema.

Usage:
  migrate_artifact_export.py EXPORT_DIR OUT_DIR [--prospects prospects.json]

EXPORT_DIR is an ArtifactData `list ... out_dir` export (agents/, events/, asks/, metrics/, pipeline/).
Writes OUT_DIR/seed.sql (paste into the Supabase SQL editor, or run with psql) and OUT_DIR/fixture.json.
The output contains client names: keep it out of the public repository.
"""
import argparse
import json
import pathlib

HUMANS = {"phoebe", "danh-trinh", "trinh-designer", "marketing"}
KIND = {"daily-report": "routine"}


def docs(folder):
    p = pathlib.Path(folder)
    return [(f.stem, json.loads(f.read_text(encoding="utf-8"))) for f in sorted(p.glob("*.json"))] if p.is_dir() else []


def lit(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, rows, key):
    if not rows:
        return ""
    cols = list(dict.fromkeys(c for r in rows for c in r))
    values = ",\n  ".join("(" + ", ".join(lit(r.get(c)) for c in cols) + ")" for r in rows)
    sets = ", ".join(f"{c} = excluded.{c}" for c in cols if c != key)
    return f"insert into public.{table} ({', '.join(cols)}) values\n  {values}\non conflict ({key}) do update set {sets};\n\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("export_dir"); ap.add_argument("out_dir"); ap.add_argument("--prospects")
    a = ap.parse_args()
    src = pathlib.Path(a.export_dir)

    agents = [{
        "id": i, "name": d.get("name") or i, "kind": "human" if i in HUMANS else KIND.get(i, "cloud"), "role": d.get("role"),
        "status": d.get("status") or "idle", "task": d.get("task"), "next": d.get("next"),
        "last_heartbeat": None if i in HUMANS else d.get("updatedAt"), "updated_at": d.get("updatedAt"),
    } for i, d in docs(src / "agents")]
    by_name = {x["name"]: x["id"] for x in agents}
    events = [{
        "ts": d.get("ts"), "agent_id": by_name.get(d.get("agent")), "kind": d.get("kind") or "note",
        "title": d.get("title") or "", "detail": d.get("detail"), "data": {"migrated_from": i},
    } for i, d in docs(src / "events")]
    approvals = [{
        "kind": "task", "title": d.get("title"), "summary": d.get("detail"), "priority": d.get("priority") or 2,
        "status": "cancelled" if d.get("status") == "done" else "pending", "created_at": d.get("createdAt"),
        "agent_id": "sales-lead", "payload": {"migrated_from": i},
    } for i, d in docs(src / "asks")]
    pipeline = [{
        "id": i, "company": d.get("company"), "market": d.get("market"), "segment": d.get("segment"), "stage": d.get("stage"),
        "next": d.get("next"), "owner": d.get("owner"), "last_touch": d.get("lastTouch"),
    } for i, d in docs(src / "pipeline")]
    metrics = [{
        "date": d.get("date"), "emails_sent": d.get("emailsSent", 0), "replies": d.get("replies", 0), "new_leads": d.get("newLeads", 0),
        "proposals": d.get("proposals", 0), "meetings": d.get("meetings", 0), "note": d.get("note"),
    } for _, d in docs(src / "metrics")]
    prospects = json.loads(pathlib.Path(a.prospects).read_text(encoding="utf-8")) if a.prospects else []

    out = pathlib.Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
    sql = "-- Generated by scripts/migrate_artifact_export.py. Contains client names: do not commit.\nbegin;\n\n"
    sql += insert("agents", agents, "id") + insert("pipeline", pipeline, "id") + insert("metrics", metrics, "date") + insert("prospects", prospects, "id")
    if events:
        cols = ["ts", "agent_id", "kind", "title", "detail", "data"]
        sql += "insert into public.events (" + ", ".join(cols) + ") values\n  " + ",\n  ".join("(" + ", ".join(lit(e[c]) for c in cols) + ")" for e in events) + ";\n\n"
    if approvals:
        cols = ["kind", "title", "summary", "priority", "status", "created_at", "agent_id", "payload"]
        sql += "insert into public.approvals (" + ", ".join(cols) + ") values\n  " + ",\n  ".join("(" + ", ".join(lit(x[c]) for c in cols) + ")" for x in approvals) + ";\n\n"
    sql += "commit;\n"
    (out / "seed.sql").write_text(sql, encoding="utf-8")
    (out / "fixture.json").write_text(json.dumps({"agents": agents, "events": events, "approvals": approvals, "pipeline": pipeline,
                                                  "metrics": metrics, "prospects": prospects}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"agents={len(agents)} events={len(events)} approvals={len(approvals)} pipeline={len(pipeline)} metrics={len(metrics)} prospects={len(prospects)}")


if __name__ == "__main__":
    main()
