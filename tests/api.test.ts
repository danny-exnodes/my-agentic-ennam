// Agent API end to end against the real schema (PGlite store mirrors the Supabase store's semantics).
import { freshDb, check } from './harness.mjs';
import { handle, sha256Hex } from '../supabase/functions/agent-api/core.ts';
import { makeStore } from './pgstore.ts';
const db = await freshDb();
await db.exec(`select set_config('request.jwt.claims', '{"role":"service_role"}', false)`);
const store = makeStore(db);
const { ok, done } = check();
const TOKEN = 'aops_' + 'x'.repeat(40);
await db.exec(`insert into agents(id,name,kind) values ('danny-laptop','Laptop','local')`);
await db.query(`insert into agent_tokens(agent_id, token_hash, allow_agents) values ('danny-laptop', $1, '{sales-lead}')`, [await sha256Hex(TOKEN)]);
const call = (m: string, p: string, body: any = {}, q = '') => handle(store, m, '/agent-api' + p, new URLSearchParams(q), 'Bearer ' + TOKEN, body);
const fails = async (pr: Promise<any>) => { try { await pr; return 0; } catch (e: any) { return e.status; } };

ok(await fails(handle(store, 'POST', '/heartbeat', new URLSearchParams(), 'Bearer nope-nope-nope-nope-nope-nope', {})) === 401, 'bad token rejected');
await call('POST', '/heartbeat', { agent: { id: 'sales-lead', name: 'Sales Lead', kind: 'cloud' }, status: 'working', task: 'Gửi email', phase: 'start', run: { id: 's1', kind: 'cloud', schedule_id: 'trig_x' } });
await call('POST', '/heartbeat', { agent: { id: 'sales-lead' }, phase: 'tool', tool: 'Bash', run: { id: 's1' } });
await call('POST', '/heartbeat', { agent: { id: 'sales-lead' }, phase: 'tool', tool: 'Gmail', run: { id: 's1' } });
let run = (await db.query(`select * from runs where id='s1'`)).rows[0] as any;
ok(run.tool_calls === 2 && run.last_tool === 'Gmail' && run.status === 'running', 'run tracks tool calls');
await call('POST', '/heartbeat', { agent: { id: 'sales-lead' }, status: 'idle', phase: 'stop', run: { id: 's1', status: 'done', summary: 'xong' } });
run = (await db.query(`select * from runs where id='s1'`)).rows[0] as any;
ok(run.status === 'done' && run.ended_at && run.summary === 'xong', 'run ends');
ok(await fails(call('POST', '/heartbeat', { agent: { id: 'someone-else' } })) === 403, 'token cannot report for other agents');
await call('POST', '/event', { agent: 'sales-lead', kind: 'email', title: 'Gửi 12 email', detail: 'A, B' });
const ap = await call('POST', '/approvals', { agent: 'sales-lead', title: 'Follow-up P2P', payload: { to: ['a@b.co'], cc: ['phoebe@exnodes.vn'], subject: 'Hi', html: '<p>x</p>' } });
ok(typeof ap.id === 'string', 'approval created');
ok(await fails(call('POST', '/approvals', { title: 'bad', payload: { to: [] } })) === 400, 'invalid email approval rejected');
ok(((await call('GET', '/approvals', {}, 'status=approved')).approvals as any[]).length === 0, 'nothing approved yet');
ok(await fails(call('POST', `/approvals/${ap.id}/result`, { status: 'executed' })) === 409, 'cannot execute unapproved');
await db.query(`update approvals set status='approved' where id=$1`, [ap.id]);
ok(((await call('GET', '/approvals', {}, 'status=approved')).approvals as any[]).length === 1, 'agent sees approved item');
await call('POST', `/approvals/${ap.id}/result`, { status: 'executed', result: { message_id: 'm1' }, title: 'Follow-up P2P' });
ok((await db.query(`select status from approvals`)).rows[0].status === 'executed', 'approval executed');
await call('POST', '/schedules/sync', { schedules: [{ id: 'trig_x', name: 'Báo cáo 17h45', cron_expression: '45 17 * * *', enabled: true, next_run_at: '2026-10-29T10:45:00Z', last_run: { status: 'ROUTINE_RUN_STATUS_SUCCEEDED', fired_at: '2026-10-28T10:45:00Z' } }] });
const sc = (await db.query(`select * from schedules where id='trig_x'`)).rows[0] as any;
ok(sc.cron === '45 17 * * *' && sc.last_run_status.includes('SUCCEEDED'), 'schedules synced');
ok((await db.query(`select count(*)::int n from schedule_runs`)).rows[0].n === 1, 'routine run recorded');
await call('POST', '/upsert/pipeline', { rows: [{ id: 'p2p', company: 'P2P', stage: 'contacted', evil: 'x' }] });
await call('POST', '/upsert/pipeline', { rows: [{ id: 'p2p', stage: 'replied' }] });
const p = (await db.query(`select * from pipeline where id='p2p'`)).rows[0] as any;
ok(p.stage === 'replied' && p.company === 'P2P', 'pipeline upsert merges');
ok(await fails(call('POST', '/upsert/pipeline', { rows: [{ id: 'x', company: 'X', stage: 'bogus' }] })) === 400, 'bad stage rejected');
ok((await call('POST', '/upsert/pipeline', { rows: [{ id: 'ghost', stage: 'won' }] })).missing === 1, 'partial update of unknown row reported');
ok(await fails(call('POST', '/upsert/admins', { rows: [{ email: 'x' }] })) === 404, 'cannot write admins via API');
await call('POST', '/upsert/metrics', { rows: [{ date: '2026-10-29', emails_sent: 37 }] });
ok((await db.query(`select emails_sent from metrics`)).rows[0].emails_sent === 37, 'metrics upsert');

done();
